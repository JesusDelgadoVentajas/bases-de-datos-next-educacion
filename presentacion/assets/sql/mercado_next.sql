-- Base de datos de ejemplo Mercado Next (PostgreSQL)
CREATE TABLE cliente (
    id          INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL UNIQUE,
    ciudad      VARCHAR(60),
    fecha_alta  DATE NOT NULL DEFAULT CURRENT_DATE,
    vip         BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE categoria (
    id        INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(60) NOT NULL UNIQUE,
    padre_id  INTEGER REFERENCES categoria (id)
);
CREATE TABLE producto (
    id            INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL,
    categoria_id  INTEGER NOT NULL REFERENCES categoria (id),
    precio        NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
    stock         INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    atributos     JSONB
);
CREATE TABLE pedido (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  INTEGER NOT NULL REFERENCES cliente (id) ON DELETE RESTRICT,
    fecha       DATE NOT NULL DEFAULT CURRENT_DATE,
    estado      VARCHAR(20) NOT NULL DEFAULT 'pendiente'
                CHECK (estado IN ('pendiente', 'enviado', 'entregado', 'cancelado'))
);
CREATE TABLE linea_pedido (
    pedido_id        INTEGER REFERENCES pedido (id) ON DELETE CASCADE,
    producto_id      INTEGER REFERENCES producto (id),
    cantidad         INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(10,2) NOT NULL,
    PRIMARY KEY (pedido_id, producto_id)
);
CREATE TABLE empleado (
    id            INTEGER PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL,
    departamento  VARCHAR(40) NOT NULL,
    salario       NUMERIC(10,2) NOT NULL,
    jefe_id       INTEGER REFERENCES empleado (id)
);

